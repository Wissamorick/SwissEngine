"""Shared round-by-round bookkeeping for every pairing system.

A concrete system only has to say *who plays whom* (`_compute_raw_pairings`)
and how it remembers that two players already met (`_mark_played`).
Everything else — colors, byes, results, scores, tiebreaks — lives here, so
that a round can either be generated by the algorithm or *replayed* from a
saved tournament with exactly the same effect (`apply_round`).

Rounds of each player (`encounters`): one entry per round in which the
player took part or was excused, ("game", opponent), ("forfeit", opponent),
("bye", None) or ("absent", None). Tiebreaks are computed from this list,
never guessed from the results matrix (a 0-0 double forfeit, or a bye worth
0 point, leaves no trace in the matrix).

Presence (Swiss and random systems): the players declared absent for a round
(`set_absences`, which also covers withdrawn players and the rounds missed by
a late arrival) are left out of the pairing and score 0 or ½ of the round.
The bye is a pseudo-player used only when the number of players present is
odd; it is created the first time it is needed. Players can be added during
the tournament (`add_player`). Without any absence or late arrival, every
round is paired exactly as before these features existed.
"""

from __future__ import annotations

import random as rd
from abc import abstractmethod

import numpy as np

from engine.common.base import BaseTournamentSystem
from engine.common.colors import effective_color
from engine.common.models import (
    GameResult,
    Pairing,
    PairingImpossibleError,
    is_forfeit,
    normalize_result,
    result_fractions,
)
from engine.common.utils import standings_swiss
from engine.config import TournamentConfig


class RoundBasedSystem(BaseTournamentSystem):
    def __init__(self, players: list[dict], config: TournamentConfig):
        self.players = players
        self.config = config
        self.n = len(players)
        self.total_rounds = config.rounds
        self._current_round = 1
        self._awaiting_results = False
        self._finished = False

        # results[i][j] = points scored by i against j (already scaled by win_value)
        self.results = np.zeros((self.n, self.n), dtype=float)

        self._pending_pairings: list[Pairing] = []
        self._win_value = 1.0

        # points that do not come from a game: absences (½ or 0 of the round)
        self.extra_points: list[float] = [0.0] * self.n
        # rounds of each player, see the module docstring
        self.encounters: list[list[tuple[str, int | None]]] = [[] for _ in range(self.n)]
        # absences of the round about to be paired: index -> fraction of the win value
        self._absent: dict[int, float] = {}
        # colors before the pending round (a forfeit cancels the colors of its game)
        self._color_before: dict[int, tuple[int, int]] = {}

        for player in self.players:
            self._init_player(player)

    def _init_player(self, player: dict) -> None:
        player["color_diff"] = 0
        player["last_color"] = 0  # +1 White, -1 Black, 0 = no game yet
        player["pts"] = 0.0
        player["TB"] = self._empty_tiebreaks()

    # ------------------------------------------------------------------ hooks
    def _empty_tiebreaks(self) -> dict[str, float]:
        return {"Bu1": 0.0, "Bu": 0.0}

    def _refresh_scores_and_tiebreaks(self) -> None:
        """Points, Buchholz and Buchholz Cut-1 from the rounds of each player.

        Buchholz: sum of the final scores of the opponents met (a forfeit
        counts as a game against its scheduled opponent); a bye or an
        absence counts as an opponent with 0 point. Cut-1: the same without
        the lowest contribution.
        """
        totals = [float(np.sum(self.results[i])) + self.extra_points[i] for i in range(self.n)]
        for i in range(self.n):
            contributions = [
                totals[opp] if opp is not None and kind in ("game", "forfeit") else 0.0
                for kind, opp in self.encounters[i]
            ]
            bu = float(sum(contributions))
            self.players[i]["pts"] = totals[i]
            self.players[i]["TB"]["Bu1"] = bu - min(contributions) if contributions else 0.0
            self.players[i]["TB"]["Bu"] = bu

    def _standings_order(self) -> list[dict]:
        return standings_swiss(self.players)

    @abstractmethod
    def _compute_raw_pairings(self, active: list[int]) -> list[tuple[int, int]]:
        """Return the pairs (player indices) of the round about to be played.

        active: the players to pair (present players, plus the bye when their
        number is odd), in index order. It is every player when nobody is
        absent (the pairing is then exactly the historical one).
        """

    def _mark_played(self, a: int, b: int) -> None:
        """Remember that a and b met (so they are not paired again)."""

    def _on_player_added(self, idx: int) -> None:
        """Hook: a player (or the bye) was appended at index idx."""

    def _on_player_removed(self, idx: int) -> None:
        """Hook: the last player (a bye created for nothing) was removed."""

    # --------------------------------------------------------------- presence
    def _bye_index(self) -> int | None:
        return next((i for i, p in enumerate(self.players) if p["Name"] == "bye"), None)

    def set_absences(self, absent: dict[int, float]) -> None:
        """Players excused from the next round: index -> fraction of the win value (0 or ½)."""
        for idx, fraction in absent.items():
            if not 0 <= idx < self.n or self.players[idx]["Name"] == "bye":
                raise ValueError(f"Invalid player index {idx}")
            if fraction not in (0.0, 0.5):
                raise ValueError(f"Invalid absence value {fraction}")
        self._absent = {int(k): float(v) for k, v in absent.items()}

    def active_players(self) -> list[int]:
        """Players to pair in the next round (creates the bye if it is needed for the first time)."""
        present = [i for i, p in enumerate(self.players) if p["Name"] != "bye" and i not in self._absent]
        bye = self._bye_index()
        if len(present) % 2 == 1:
            if bye is None:
                bye = self._append_player({"Name": "bye", "Elo": 0, "strength": 0})
                self._bye_created = True
            return sorted(present + [bye])
        return present

    def _append_player(self, player: dict) -> int:
        self.players.append(player)
        self._init_player(player)
        self.n += 1
        self.results = np.pad(self.results, ((0, 1), (0, 1)))
        self.extra_points.append(0.0)
        self.encounters.append([])
        idx = self.n - 1
        self._on_player_added(idx)
        return idx

    def _remove_last_player(self) -> None:
        idx = self.n - 1
        self._on_player_removed(idx)
        self.players.pop()
        self.n -= 1
        self.results = self.results[: self.n, : self.n]
        self.extra_points.pop()
        self.encounters.pop()

    def add_player(self, player: dict, missed: list[float]) -> int:
        """Add a player during the tournament (late arrival).

        missed: points scored for each round already played (one entry per
        round, already multiplied by the win value of the round).
        """
        if self._awaiting_results:
            raise RuntimeError("A round is awaiting results")
        idx = self._append_player(player)
        self.extra_points[idx] = float(sum(missed))
        self.encounters[idx] = [("absent", None) for _ in missed]
        self._refresh_scores_and_tiebreaks()
        return idx

    # ------------------------------------------------------------- properties
    @property
    def current_round(self) -> int:
        return self._current_round

    @property
    def is_finished(self) -> bool:
        return self._finished

    @property
    def awaiting_results(self) -> bool:
        return self._awaiting_results

    @property
    def pending_pairings(self) -> list[Pairing]:
        return list(self._pending_pairings)

    # ----------------------------------------------------------------- rounds
    def _prepare_round(self) -> None:
        if self._finished:
            raise RuntimeError("Tournament is already finished")
        if self._awaiting_results:
            raise RuntimeError("Results for the current round have not been entered yet")
        if self._current_round > self.total_rounds:
            self._finished = True
            raise RuntimeError("No rounds remaining")
        self._win_value = self.config.win_value(self._current_round)
        self._refresh_scores_and_tiebreaks()

    def generate_round(self) -> list[Pairing]:
        self._prepare_round()
        self._bye_created = False
        active = self.active_players()
        if sum(1 for i in active if self.players[i]["Name"] != "bye") < 2:
            if self._bye_created:
                self._remove_last_player()
            raise PairingImpossibleError(
                f"Impossible d'apparier la ronde {self._current_round} : il faut au moins "
                "2 joueurs présents."
            )
        raw_pairings = self._compute_raw_pairings(active)
        # Every active player (bye included) must be in exactly one pair.
        # Otherwise nothing is recorded: some players would silently miss the
        # round. Guaranteed without absences when the number of rounds is at
        # most m / 2 (m = players, bye included): see Tournament.max_safe_rounds.
        seated = [x for pair in raw_pairings for x in pair]
        if sorted(seated) != active:
            missing = [
                i for i in active if i not in set(seated) and self.players[i]["Name"] != "bye"
            ]
            if self._bye_created:
                self._remove_last_player()
            raise PairingImpossibleError(
                f"Impossible d'apparier la ronde {self._current_round} : l'algorithme n'a pas "
                f"trouvé d'adversaire inédit pour {max(len(missing), 1)} joueur(s) présent(s). "
                "Le tournoi est inchangé. Les joueurs présents se sont déjà presque tous "
                "rencontrés : il y a trop de rondes pour le nombre de joueurs présents. Vous "
                "pouvez modifier les absences ou terminer le tournoi ici."
            )
        return self._register_round(raw_pairings, assign_colors=True)

    def apply_round(self, pairs: list[tuple[int, int]]) -> list[Pairing]:
        """Play a round whose pairings are imposed (white index, black index).

        Used to rebuild a saved tournament: colors are taken as given.
        """
        self._prepare_round()
        seen: set[int] = set()
        for a, b in pairs:
            for x in (a, b):
                if not 0 <= x < self.n:
                    raise ValueError(f"Invalid player index {x}")
                if x in seen:
                    raise ValueError(f"Player '{self.players[x]['Name']}' appears twice in the same round")
                if x in self._absent:
                    raise ValueError(f"Player '{self.players[x]['Name']}' is absent but paired")
                seen.add(x)
        return self._register_round(pairs, assign_colors=False)

    def _player_snapshot(self, idx: int) -> tuple[int, float]:
        p = self.players[idx]
        return int(p.get("Elo", 0)), float(p.get("pts", 0.0))

    def _choose_white(self, a: int, b: int, table: int) -> tuple[int, int]:
        """Return (white, black) for a pair of real players.

        1. The player who needs White more (lower effective color, see
           engine/common/colors.py) gets White.
        2. Round 1 (nobody has played): colors alternate from table to table,
           as in FIDE practice. The higher-ranked player of table 1 gets the
           color chosen in config.first_board_color ("random": drawn by lot
           once for the round), the one of table 2 the other color, etc.
        3. Later exact ties (same cd and same last color): drawn by lot.
        """
        ea, eb = effective_color(self.players[a]), effective_color(self.players[b])
        if ea != eb:
            return (a, b) if ea < eb else (b, a)
        if self._current_round == 1:
            top, other = sorted((a, b), key=self._rank_key)
            top_white = self._first_board_white if table % 2 == 1 else not self._first_board_white
            return (top, other) if top_white else (other, top)
        return (a, b) if rd.random() <= 0.5 else (b, a)

    def _rank_key(self, idx: int) -> tuple:
        """Pairing order: points, then Elo, then starting rank."""
        p = self.players[idx]
        return (-float(p.get("pts", 0.0)), -int(p.get("Elo", 0)), idx)

    def _register_round(self, raw_pairings: list[tuple[int, int]], assign_colors: bool) -> list[Pairing]:
        pairings: list[Pairing] = []
        if assign_colors and self._current_round == 1:
            choice = self.config.first_board_color
            self._first_board_white = rd.random() < 0.5 if choice == "random" else choice == "white"
        # absent players score their fraction of the round at once (like the bye)
        for idx, fraction in sorted(self._absent.items()):
            self.extra_points[idx] += fraction * self._win_value
            self.encounters[idx].append(("absent", None))
        self._absent = {}
        self._color_before = {}
        for table_idx, (a, b) in enumerate(raw_pairings, start=1):
            self._mark_played(a, b)

            # Bye always on Black side
            if self.players[a]["Name"] == "bye":
                a, b = b, a
            if self.players[b]["Name"] == "bye":
                # += : in a double round-robin a player is exempt once per leg
                self.results[a][b] += self.config.bye_value * self._win_value
                self.encounters[a].append(("bye", None))
                w_elo, w_pts = self._player_snapshot(a)
                pairings.append(
                    Pairing(
                        table=table_idx,
                        white_name=self.players[a]["Name"],
                        black_name="bye",
                        white_index=a,
                        black_index=b,
                        is_bye=True,
                        white_elo=w_elo,
                        white_pts=w_pts,
                    )
                )
                continue

            if assign_colors:
                a, b = self._choose_white(a, b, table_idx)

            for x in (a, b):
                self._color_before[x] = (self.players[x]["color_diff"], self.players[x]["last_color"])
            self.players[a]["color_diff"] += 1
            self.players[b]["color_diff"] -= 1
            self.players[a]["last_color"] = 1
            self.players[b]["last_color"] = -1

            w_elo, w_pts = self._player_snapshot(a)
            b_elo, b_pts = self._player_snapshot(b)
            pairings.append(
                Pairing(
                    table=table_idx,
                    white_name=self.players[a]["Name"],
                    black_name=self.players[b]["Name"],
                    white_index=a,
                    black_index=b,
                    is_bye=False,
                    white_elo=w_elo,
                    black_elo=b_elo,
                    white_pts=w_pts,
                    black_pts=b_pts,
                )
            )

        self._pending_pairings = pairings
        self._awaiting_results = True
        return list(pairings)

    def enter_results(self, results: list[GameResult]) -> None:
        if not self._awaiting_results:
            raise RuntimeError("No round is awaiting results")

        pending_games = [p for p in self._pending_pairings if not p.is_bye]
        if len(results) != len(pending_games):
            raise ValueError(
                f"Expected {len(pending_games)} results (non-bye games), got {len(results)}"
            )

        by_table = {r.table: r for r in results}
        scores = {}
        for pairing in pending_games:
            if pairing.table not in by_table:
                raise ValueError(f"Missing result for table {pairing.table}")
            scores[pairing.table] = normalize_result(by_table[pairing.table].white_score, pairing.table)

        for pairing in pending_games:
            res = scores[pairing.table]
            a, b = pairing.white_index, pairing.black_index
            w, bl = result_fractions(res)
            # += : in a double round-robin the same two players meet twice
            # (Swiss systems never repeat a pair, so this changes nothing there)
            self.results[a][b] += w * self._win_value
            self.results[b][a] += bl * self._win_value
            kind = "forfeit" if is_forfeit(res) else "game"
            self.encounters[a].append((kind, b))
            self.encounters[b].append((kind, a))
            if kind == "forfeit":
                # the game was not played: its colors do not count
                for x in (a, b):
                    if x in self._color_before:
                        self.players[x]["color_diff"], self.players[x]["last_color"] = self._color_before[x]

        self._refresh_scores_and_tiebreaks()
        self._pending_pairings = []
        self._awaiting_results = False
        self._current_round += 1

        if self._current_round > self.total_rounds:
            self._finished = True

    def get_standings(self) -> list[dict]:
        self._refresh_scores_and_tiebreaks()
        ranking = self._standings_order()
        return [p for p in ranking if p["Name"] != "bye"]
